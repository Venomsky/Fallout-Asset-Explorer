    public static IReadOnlyList<FormatCoverageDefinition> All => Definitions;

    private static FormatCoverageDefinition Format(
        string id,
        string name,
        params FormatCoverageCapability[] capabilities) =>
        new(id, name, Array.AsReadOnly(capabilities));

    private static FormatCoverageCapability Capability(
        FormatCoverageCategory category,
        FormatCoverageStatus status,
        string rationale,
        FormatCoverageConfidence confidence,
        params FormatCoverageEvidence[] evidence) =>
        new(
            category,
            FormatCoverageWeights.GetWeight(category),
            status,
            rationale,
            confidence,
            Array.AsReadOnly(evidence));

    private static FormatCoverageEvidence Code(string path, string note) =>
        Evidence(path, CoverageEvidenceSource.ProductionCode, CoverageDataVerification.Unverified, note);

    private static FormatCoverageEvidence Synthetic(string path, string note) =>
        Evidence(path, CoverageEvidenceSource.Test, CoverageDataVerification.SyntheticData, note);

